if __name__ == "__main__":
    from ..config import get_config
    from ..inference.engine import InferenceEngine
    from ..model.transformer import LyceumLM

    cfg = get_config("nano")
    tok = BPETokenizer(special_tokens=cfg.tokenizer.special_tokens)
    tok.train(
        'the quick brown fox. {"tool": "calculator", "args": {"x": "1"}} '
        "weather search calculator email " * 30,
        vocab_size=400,
    )
    model = LyceumLM(cfg.model, vocab_size=tok.vocab_size).eval()
    eng = InferenceEngine(model, tok, cfg)

    print("== ChoiceConstraint ==")
    options = ["calculator", "weather", "search"]
    cc = ChoiceConstraint(options, tok)
    seen = set()
    # sample a few times under temperature to exercise different paths
    for temp in (0.0, 1.0, 1.5, 2.0):
        out = constrained_generate(eng, "pick a tool:", cc,
                                    max_new_tokens=32, temperature=temp)
        assert out in options, f"ChoiceConstraint produced {out!r} not in {options}"
        seen.add(out)
        print(f"  temp={temp}: -> {out!r}  (in options: True)")
    print(f"  distinct options reached: {sorted(seen)}")

    print("\n== JSONConstraint ==")
    jc = JSONConstraint(tok, max_str_len=12)
    ok_count = 0
    for temp in (0.0, 1.0, 2.0):
        out = constrained_generate(eng, "emit a tool call:", jc,
                                    max_new_tokens=96, temperature=temp)
        parseable = False
        try:
            obj = json.loads(out)
            parseable = isinstance(obj, dict) and "tool" in obj and "args" in obj
        except Exception:
            parseable = False
        ok_count += int(parseable)
        print(f"  temp={temp}: {out!r}  parseable={parseable}")
    assert ok_count >= 1, "JSONConstraint never produced parseable JSON"
    print(f"  parseable outputs: {ok_count}/3")

    print("\nself-test OK: ChoiceConstraint always in-options; JSON parseable.")
